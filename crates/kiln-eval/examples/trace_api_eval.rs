//! Standalone production-trace suite runner for OpenAI-compatible chat APIs.
//!
//! This intentionally lives in `kiln-eval` instead of `kiln-server`: it loads
//! an `EvalSuite`, sends the suite's chat messages/tools to an external API,
//! and scores responses locally with the same scorer stack the Kiln server
//! uses. It is useful for comparing a generated production trace suite against
//! hosted models without starting a Kiln model server.

use std::collections::BTreeMap;
use std::path::PathBuf;
use std::time::Instant;

use anyhow::{Context, Result, bail};
use clap::Parser;
use kiln_eval::qwen3::{extract_first_tool_call, validate_against_schema};
use kiln_eval::scorers::{NoopJudgeRunner, Scorer, score_completion};
use kiln_eval::{
    AggregateMetrics, EvalGenerationParams, EvalJobState, EvalOutcomeKind, EvalResult, EvalSuite,
    ExampleOutcome, SuiteResult,
};
use serde_json::{Value, json};

#[derive(Parser, Debug)]
#[command(
    name = "trace_api_eval",
    about = "Run an EvalSuite against OpenAI-compatible chat/completions APIs"
)]
struct Args {
    /// EvalSuite JSON generated by `kiln-eval trace-suite`.
    #[arg(long)]
    suite: PathBuf,
    /// Model name to pass to the API. Repeat to compare multiple models.
    #[arg(long = "model", required = true)]
    models: Vec<String>,
    /// API base URL, e.g. https://api.openai.com/v1 or a local compatible server.
    #[arg(
        long,
        env = "OPENAI_API_BASE",
        default_value = "https://api.openai.com/v1"
    )]
    api_base: String,
    /// Env var containing the bearer token. Ignored when unset/empty.
    #[arg(long, default_value = "OPENAI_API_KEY")]
    api_key_env: String,
    /// Bearer token value. Prefer --api-key-env for shell history hygiene.
    #[arg(long)]
    api_key: Option<String>,
    /// Override generation temperature for every example.
    #[arg(long)]
    temperature: Option<f32>,
    /// Override max_tokens for every example.
    #[arg(long)]
    max_tokens: Option<usize>,
    /// Evaluate at most this many suite examples.
    #[arg(long)]
    limit: Option<usize>,
    /// Do not send the suite/example tool catalogue to the API.
    #[arg(long)]
    no_tools: bool,
    /// Optional OpenAI-compatible tool_choice value: auto, required, or none.
    #[arg(long)]
    tool_choice: Option<String>,
    /// Merge an arbitrary JSON object into every request body.
    #[arg(long)]
    extra_body_json: Option<String>,
    /// Write the full EvalResult JSON here. If omitted, only a summary prints.
    #[arg(long)]
    output: Option<PathBuf>,
    /// Print the full EvalResult JSON to stdout.
    #[arg(long)]
    json: bool,
}

#[tokio::main]
async fn main() -> Result<()> {
    let args = Args::parse();
    let suite = EvalSuite::load_json(&args.suite)
        .with_context(|| format!("loading suite {}", args.suite.display()))?;
    let api_key = args
        .api_key
        .clone()
        .or_else(|| std::env::var(&args.api_key_env).ok())
        .filter(|s| !s.is_empty());
    let extra_body = parse_extra_body(args.extra_body_json.as_deref())?;
    let client = reqwest::Client::builder().build()?;
    let started_at = chrono::Utc::now();

    let mut runs = Vec::new();
    for model in &args.models {
        runs.push(
            run_model(
                &client,
                &suite,
                model,
                &args,
                api_key.as_deref(),
                extra_body.as_ref(),
            )
            .await?,
        );
    }

    let result = EvalResult {
        job_id: format!("trace-api-{}", uuid::Uuid::new_v4()),
        state: EvalJobState::Completed,
        runs,
        progress: None,
        error: None,
    };

    if let Some(path) = args.output.as_ref() {
        std::fs::write(path, serde_json::to_vec_pretty(&result)?)
            .with_context(|| format!("writing {}", path.display()))?;
    }
    if args.json {
        println!("{}", serde_json::to_string_pretty(&result)?);
    } else {
        print_summary(&result, started_at);
    }
    Ok(())
}

async fn run_model(
    client: &reqwest::Client,
    suite: &EvalSuite,
    model: &str,
    args: &Args,
    api_key: Option<&str>,
    extra_body: Option<&Value>,
) -> Result<SuiteResult> {
    let run_started = chrono::Utc::now();
    let run_clock = Instant::now();
    let mut outcomes = Vec::new();
    let mut weights = BTreeMap::new();
    let mut tags_by_example = BTreeMap::new();
    let mut scorer_kind_by_example = BTreeMap::new();
    let mut target_tool_by_example = BTreeMap::new();
    let mut predicted_tool_by_outcome = BTreeMap::new();
    let mut schema_violations_by_outcome = BTreeMap::new();

    let examples = suite
        .examples
        .iter()
        .take(args.limit.unwrap_or(usize::MAX))
        .collect::<Vec<_>>();

    let total_examples = examples.len();
    for (idx, example) in examples.into_iter().enumerate() {
        let example_id = example.resolved_id();
        let scorer = example.scorer.as_ref().unwrap_or(&suite.default_scorer);
        weights.insert(example_id.clone(), example.weight);
        tags_by_example.insert(example_id.clone(), example.tags.clone());
        scorer_kind_by_example.insert(example_id.clone(), scorer.kind_label());
        if matches!(scorer, Scorer::ToolCall { .. }) {
            if let Some(target) = example.target.as_deref() {
                if let Some(call) = extract_first_tool_call(target) {
                    target_tool_by_example.insert(example_id.clone(), call.name);
                }
            }
        }

        let gen_params = effective_generation(suite, example, args);
        let n = gen_params.n.max(1);
        for completion_idx in 0..n {
            let start = Instant::now();
            let response = call_chat_api(
                client,
                suite,
                example,
                model,
                &gen_params,
                args,
                api_key,
                extra_body,
            )
            .await;
            let latency_ms = start.elapsed().as_secs_f64() * 1000.0;
            let mut outcome = match response {
                Ok(resp) => score_api_response(
                    scorer,
                    example,
                    &example_id,
                    completion_idx,
                    resp,
                    latency_ms,
                    &mut predicted_tool_by_outcome,
                    &mut schema_violations_by_outcome,
                    suite,
                )?,
                Err(err) => ExampleOutcome {
                    example_id: example_id.clone(),
                    completion_index: completion_idx,
                    completion_text: String::new(),
                    kind: EvalOutcomeKind::Error,
                    score: 0.0,
                    detail: Some(format!("generation failed: {err}")),
                    prompt_tokens: None,
                    completion_tokens: None,
                    latency_ms: Some(latency_ms),
                    tags: example.tags.clone(),
                    metadata: example.metadata.clone(),
                    reasoning_text: None,
                    unclosed_thinking: false,
                },
            };
            outcome.completion_index = completion_idx;
            outcomes.push(outcome);
        }
        eprintln!(
            "model={} example={}/{} outcomes={}",
            model,
            idx + 1,
            total_examples,
            outcomes.len()
        );
    }

    let elapsed_secs = run_clock.elapsed().as_secs_f64();
    let metrics = AggregateMetrics::compute_with_tools_full(
        &outcomes,
        &weights,
        &tags_by_example,
        &scorer_kind_by_example,
        &target_tool_by_example,
        &predicted_tool_by_outcome,
        &schema_violations_by_outcome,
        elapsed_secs,
    );
    Ok(SuiteResult {
        suite_name: suite.name.clone(),
        adapter: Some(model.to_string()),
        metrics,
        outcomes,
        started_at: run_started.to_rfc3339(),
        finished_at: chrono::Utc::now().to_rfc3339(),
        suite_hash: suite_hash(suite)?,
    })
}

fn effective_generation(
    suite: &EvalSuite,
    example: &kiln_eval::EvalExample,
    args: &Args,
) -> EvalGenerationParams {
    let mut gen_params = example
        .generation
        .as_ref()
        .unwrap_or(&suite.generation)
        .clone();
    if let Some(temperature) = args.temperature {
        gen_params.temperature = temperature;
    }
    if let Some(max_tokens) = args.max_tokens {
        gen_params.max_tokens = max_tokens;
    }
    gen_params
}

async fn call_chat_api(
    client: &reqwest::Client,
    suite: &EvalSuite,
    example: &kiln_eval::EvalExample,
    model: &str,
    gen_params: &EvalGenerationParams,
    args: &Args,
    api_key: Option<&str>,
    extra_body: Option<&Value>,
) -> Result<ApiCompletion> {
    let mut body = json!({
        "model": model,
        "messages": example.messages,
        "temperature": gen_params.temperature,
        "max_tokens": gen_params.max_tokens,
        "n": 1,
    });
    if let Some(seed) = gen_params.seed {
        body["seed"] = json!(seed);
    }
    if !gen_params.stop.is_empty() {
        body["stop"] = json!(gen_params.stop);
    }
    if !args.no_tools {
        if let Some(tools) = example.effective_tools(suite.tools.as_deref()) {
            if !tools.is_empty() {
                body["tools"] = json!(tools);
                if let Some(choice) = args.tool_choice.as_ref() {
                    body["tool_choice"] = json!(choice);
                }
            }
        }
    }
    if let Some(extra) = extra_body {
        merge_object(&mut body, extra)?;
    }

    let url = format!("{}/chat/completions", args.api_base.trim_end_matches('/'));
    let mut req = client.post(url).json(&body);
    if let Some(api_key) = api_key {
        req = req.bearer_auth(api_key);
    }
    let resp = req.send().await.context("POST /chat/completions")?;
    let status = resp.status();
    let text = resp.text().await.unwrap_or_default();
    if !status.is_success() {
        bail!("API returned {status}: {text}");
    }
    let value: Value = serde_json::from_str(&text).context("parsing API response JSON")?;
    Ok(ApiCompletion::from_response(value)?)
}

fn score_api_response(
    scorer: &Scorer,
    example: &kiln_eval::EvalExample,
    example_id: &str,
    completion_idx: usize,
    response: ApiCompletion,
    latency_ms: f64,
    predicted_tool_by_outcome: &mut BTreeMap<(String, usize), String>,
    schema_violations_by_outcome: &mut BTreeMap<(String, usize), (u32, u32)>,
    suite: &EvalSuite,
) -> Result<ExampleOutcome> {
    if matches!(scorer, Scorer::ToolCall { .. }) {
        let parsed = extract_first_tool_call(&response.completion_text);
        let predicted = parsed
            .as_ref()
            .map(|c| c.name.clone())
            .unwrap_or_else(|| "<none>".to_string());
        predicted_tool_by_outcome.insert((example_id.to_string(), completion_idx), predicted);
        if let Some(call) = parsed.as_ref() {
            if let Some(catalogue) = example.effective_tools(suite.tools.as_deref()) {
                if let Some(chk) = validate_against_schema(call, catalogue) {
                    if !chk.is_clean() {
                        schema_violations_by_outcome.insert(
                            (example_id.to_string(), completion_idx),
                            (
                                chk.missing_required.len() as u32,
                                chk.extra_unknown.len() as u32,
                            ),
                        );
                    }
                }
            }
        }
    }
    let mut outcome =
        score_completion(scorer, example, &response.completion_text, &NoopJudgeRunner)?;
    outcome.completion_index = completion_idx;
    outcome.prompt_tokens = response.prompt_tokens;
    outcome.completion_tokens = response.completion_tokens;
    outcome.latency_ms = Some(latency_ms);
    Ok(outcome)
}

struct ApiCompletion {
    completion_text: String,
    prompt_tokens: Option<usize>,
    completion_tokens: Option<usize>,
}

impl ApiCompletion {
    fn from_response(value: Value) -> Result<Self> {
        let choice = value
            .get("choices")
            .and_then(|v| v.as_array())
            .and_then(|choices| choices.first())
            .context("response had no choices[0]")?;
        let message = choice
            .get("message")
            .context("response choices[0] had no message")?;
        let content = message_text(message.get("content"));
        let reasoning = message_text(message.get("reasoning_content"));
        let tool_calls = message.get("tool_calls").and_then(|v| v.as_array());
        let mut answer = String::new();
        if let Some(reasoning) = reasoning.filter(|s| !s.trim().is_empty()) {
            answer.push_str("<think>\n");
            answer.push_str(&reasoning);
            answer.push_str("\n</think>\n\n");
        }
        if let Some(content) = content.filter(|s| !s.trim().is_empty()) {
            answer.push_str(&content);
            answer.push('\n');
        }
        if let Some(tool_calls) = tool_calls.filter(|calls| !calls.is_empty()) {
            answer.push_str(&serde_json::to_string(
                &json!({ "tool_calls": tool_calls }),
            )?);
        }
        let usage = value.get("usage");
        Ok(Self {
            completion_text: answer,
            prompt_tokens: usage
                .and_then(|u| u.get("prompt_tokens"))
                .and_then(|v| v.as_u64())
                .map(|v| v as usize),
            completion_tokens: usage
                .and_then(|u| u.get("completion_tokens"))
                .and_then(|v| v.as_u64())
                .map(|v| v as usize),
        })
    }
}

fn message_text(value: Option<&Value>) -> Option<String> {
    match value? {
        Value::Null => None,
        Value::String(s) => Some(s.clone()),
        Value::Array(parts) => {
            let text = parts
                .iter()
                .filter_map(|part| {
                    part.get("text")
                        .and_then(|v| v.as_str())
                        .or_else(|| part.as_str())
                })
                .collect::<Vec<_>>()
                .join("");
            (!text.is_empty()).then_some(text)
        }
        other => Some(other.to_string()),
    }
}

fn parse_extra_body(raw: Option<&str>) -> Result<Option<Value>> {
    let Some(raw) = raw else {
        return Ok(None);
    };
    let value: Value = serde_json::from_str(raw).context("parsing --extra-body-json")?;
    if !value.is_object() {
        bail!("--extra-body-json must be a JSON object");
    }
    Ok(Some(value))
}

fn merge_object(target: &mut Value, extra: &Value) -> Result<()> {
    let target = target
        .as_object_mut()
        .context("internal request body was not an object")?;
    let extra = extra
        .as_object()
        .context("--extra-body-json must be a JSON object")?;
    for (key, value) in extra {
        target.insert(key.clone(), value.clone());
    }
    Ok(())
}

fn suite_hash(suite: &EvalSuite) -> Result<String> {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(serde_json::to_vec(suite)?);
    let digest = h.finalize();
    let mut out = String::with_capacity("sha256:".len() + digest.len() * 2);
    out.push_str("sha256:");
    for byte in digest {
        out.push_str(&format!("{byte:02x}"));
    }
    Ok(out)
}

fn print_summary(result: &EvalResult, started_at: chrono::DateTime<chrono::Utc>) {
    println!(
        "trace-api-eval completed in {:.2}s",
        (chrono::Utc::now() - started_at).num_milliseconds() as f64 / 1000.0
    );
    for run in &result.runs {
        let ci = &run.metrics.accuracy_confidence_interval;
        println!(
            "{:<32} accuracy={:.1}% pass={}/{} score={:.3} ci95=[{:.1}%, {:.1}%] invalid={} error={} non_xml={}",
            run.adapter.as_deref().unwrap_or("<base>"),
            run.metrics.accuracy * 100.0,
            run.metrics.num_pass,
            run.metrics.num_examples,
            run.metrics.mean_score,
            ci.lower * 100.0,
            ci.upper * 100.0,
            run.metrics.num_invalid,
            run.metrics.num_error,
            run.metrics.num_non_xml_tool_calls,
        );
    }
}
